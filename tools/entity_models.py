def paint(parts, tex_w, tex_h, glow=False):
    img = Image.new("RGBA", (tex_w, tex_h), (0, 0, 0, 0))
    px = img.load()
    for p in parts:
        for c in p.cubes:
            painter = c.glow if glow else c.painter
            if painter is None:
                continue
            for face, (fx, fy, fw, fh) in c.faces().items():
                for j in range(int(fh)):
                    for i in range(int(fw)):
                        x, y = int(fx) + i, int(fy) + j
                        if 0 <= x < tex_w and 0 <= y < tex_h:
                            color = painter(face, i, j, int(fw), int(fh))
                            if color is not None:
                                px[x, y] = color if len(color) == 4 else (*color, 255)
    return img


# ----------------------------------------------------------------------------------------------- painters

def surface(pal, seed, shading=True, speckle=0.35, top_light=1.12, bottom_dark=0.8):
    rng = random.Random(seed)
    cache = {}

    def painter(face, i, j, w, h):
        key = (face, i, j, w, h)
        if key not in cache:
            base = noise_pick(pal, rng, speckle)
            if shading:
                if face == "top":
                    base = shade(base, top_light)
                elif face == "bottom":
                    base = shade(base, bottom_dark)
                elif face in ("left", "right"):
                    base = shade(base, 0.92)
            cache[key] = base
        return cache[key]

    return painter


def layered(*painters):
    """First painter returning a colour wins."""

    def painter(face, i, j, w, h):
        for p in painters:
            c = p(face, i, j, w, h)
            if c is not None:
                return c
        return None

    return painter


def on(face_names, fn):
    def painter(face, i, j, w, h):
        if face in face_names:
            return fn(i, j, w, h)
        return None

    return painter


