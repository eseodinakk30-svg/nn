"""Entity models for Dunes & Relics.

Each model is described once, here, and this script generates both the Java model class
(the LayerDefinition plus the animation code) and the matching entity texture, so the
UV layout of the texture always agrees with the boxes of the model.

Run from the repository root:  python3 tools/entity_models.py
"""
